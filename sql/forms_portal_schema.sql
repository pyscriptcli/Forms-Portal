create table if not exists "forms-portal-rfp_sequence" (
  id bigint generated by default as identity primary key,
  reference_month varchar(6) not null,
  sequence_number integer not null unique,
  base_reference varchar(32) not null unique,
  submission_path varchar(16) not null default 'option-a',
  entity_code varchar(16) not null default '',
  payee_token varchar(160) not null default '',
  revision_count integer not null default 0,
  clickup_task_id varchar(64),
  created_at timestamptz not null default now(),
  constraint forms_portal_rfp_sequence_number_check check (sequence_number between 1 and 9999),
  constraint forms_portal_rfp_sequence_path_check check (submission_path = 'option-a')
);

create sequence if not exists forms_portal_rfp_sequence_number_seq start 1 maxvalue 9999 no cycle;

select setval(
  'forms_portal_rfp_sequence_number_seq',
  case when coalesce((select max(sequence_number) from "forms-portal-rfp_sequence"), 0) = 0 then 1
       else (select max(sequence_number) from "forms-portal-rfp_sequence") end,
  case when coalesce((select max(sequence_number) from "forms-portal-rfp_sequence"), 0) > 0 then true else false end
);

create or replace function forms_portal_allocate_rfp_sequence(
  p_reference_month varchar(6),
  p_entity_code varchar(16),
  p_payee_token varchar(160)
) returns table (base_reference varchar(32), sequence_number integer)
language plpgsql security definer as $$
declare next_number integer;
begin
  select nextval('forms_portal_rfp_sequence_number_seq')::integer into next_number;
  if next_number > 9999 then raise exception 'RFP sequence limit reached'; end if;
  insert into "forms-portal-rfp_sequence" (reference_month, sequence_number, base_reference, entity_code, payee_token)
  values (p_reference_month, next_number, 'RFP-' || p_reference_month || '-' || lpad(next_number::text, 4, '0'), p_entity_code, p_payee_token);
  return query select 'RFP-' || p_reference_month || '-' || lpad(next_number::text, 4, '0'), next_number;
end; $$;

