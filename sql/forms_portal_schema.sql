create table if not exists "forms-portal-RBAC" (
  id bigint generated by default as identity primary key,
  user_id varchar(120) not null unique,
  name varchar(160) not null,
  email varchar(255) not null unique,
  department varchar(160) not null default 'Operations',
  role varchar(32) not null,
  status varchar(16) not null default 'active',
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint forms_portal_rbac_role_check
    check (role in ('admin', 'approver', 'finance', 'requestor')),
